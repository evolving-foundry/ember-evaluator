import { build } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
await mkdir(new URL("scripts/network/", root), { recursive: true });
for (const [source, destination] of [["bootstrap.ts", "bootstrap.mjs"], ["ssh-proxy.ts", "ssh-proxy.js"]]) {
  await build({ entryPoints: [fileURLToPath(new URL(source === "bootstrap.ts" ? "src/application/network/bootstrap.ts" : `src/infrastructure/network/${source}`, root))],
    outfile: fileURLToPath(new URL(`scripts/network/${destination}`, root)),
    bundle: true, platform: "node", format: "esm", target: "node24", minify: false, legalComments: "eof",
    banner: { js: "// Generated by scripts/build-network-bootstrap.mjs. Do not edit directly.\nimport { createRequire as bootstrapRequire } from 'node:module'; const require = bootstrapRequire(import.meta.url);" } });
}
// Keep the bundled YAML parser's license next to the dependency-free launcher.
await writeFile(new URL("scripts/network/LICENSE-yaml", root), await readFile(new URL("node_modules/yaml/LICENSE", root)));
